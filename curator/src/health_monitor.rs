    /// Check sync status between L3 and mirror registries
    pub async fn check_mirror_sync(&self) -> Result<MirrorSyncStatus, MonitorError> {
        // Read L3 registry nonce
        let tx_l3 = TransactionRequest::new()
            .to(self.l3_registry_address)
            .data(SELECTOR_REGISTRY_NONCE.to_vec());

        let result_l3 = tokio::time::timeout(
            self.rpc_timeout,
            self.l3_provider.call(&tx_l3.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("L3 registryNonce() call".to_string()))?
        .map_err(|e| {
            MonitorError::L3ConnectionError(format!("L3 registryNonce() call failed: {}", e))
        })?;

        if result_l3.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid L3 registryNonce response".to_string(),
            ));
        }

        let l3_nonce = U256::from_big_endian(&result_l3[0..32]).as_u64();

        // Read mirror registry nonce
        let tx_mirror = TransactionRequest::new()
            .to(self.mirror_registry_address)
            .data(SELECTOR_REGISTRY_NONCE.to_vec());

        let result_mirror = tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_mirror.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("mirror registryNonce() call".to_string()))?
        .map_err(|e| {
            MonitorError::ReadError(format!("mirror registryNonce() call failed: {}", e))
        })?;

        if result_mirror.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid mirror registryNonce response".to_string(),
            ));
        }

        let mirror_nonce = U256::from_big_endian(&result_mirror[0..32]).as_u64();

        // Read active counts (L3) — use data-node if available, otherwise direct RPC
        let l3_active_count = if let Some(ref dn) = self.data_node_client {
            match dn.get_active_oracle_count().await {
                Ok(count) => {
                    debug!(count, "L3 active oracle count via data-node");
                    count
                }
                Err(e) => {
                    warn!(error = %e, "Data-node activeOracleCount failed, falling back to RPC");
                    self.rpc_read_l3_active_oracle_count().await
                }
            }
        } else {
            self.rpc_read_l3_active_oracle_count().await
        };

        // Read active counts (mirror)
        let tx_mirror_count = TransactionRequest::new()
            .to(self.mirror_registry_address)
            .data(SELECTOR_ACTIVE_COUNT.to_vec());

        let mirror_active_count = match tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_mirror_count.into(), None),
        )
        .await
        {
            Ok(Ok(result)) if result.len() >= 32 => {
                U256::from_big_endian(&result[0..32]).as_u64()
            }
            _ => 0, // Default if call fails
        };

        let nonce_gap = l3_nonce as i64 - mirror_nonce as i64;
        let is_synced = nonce_gap == 0;

        Ok(MirrorSyncStatus {
            l3_nonce,
            mirror_nonce,
            nonce_gap,
            is_synced,
            l3_active_count,
            mirror_active_count,
        })
    }

