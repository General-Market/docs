/// Alert severity levels
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Severity {
    /// Routine status updates
    Info,
    /// Conditions requiring attention
    Warning,
    /// Conditions requiring immediate action
    Critical,
}

/// Alert categories
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AlertCategory {
    /// Position health alerts
    Position,
    /// Oracle freshness alerts
    Oracle,
    /// Mirror registry sync alerts
    Mirror,
    /// Vault metrics alerts
    Vault,
}

/// An alert generated by the health monitor
