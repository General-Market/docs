    /// Check freshness of an oracle
    pub async fn check_oracle_freshness(
        &self,
        oracle_address: Address,
        itp_address: Address,
    ) -> Result<OracleStatus, MonitorError> {
        // Read lastUpdated
        let tx_last_updated = TransactionRequest::new()
            .to(oracle_address)
            .data(SELECTOR_LAST_UPDATED.to_vec());

        let result_last_updated = tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_last_updated.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("lastUpdated() call".to_string()))?
        .map_err(|e| MonitorError::ReadError(format!("lastUpdated() call failed: {}", e)))?;

        if result_last_updated.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid lastUpdated response".to_string(),
            ));
        }

        let last_updated = U256::from_big_endian(&result_last_updated[0..32]).as_u64();

        // Read currentPrice
        let tx_price = TransactionRequest::new()
            .to(oracle_address)
            .data(SELECTOR_CURRENT_PRICE.to_vec());

        let result_price = tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_price.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("currentPrice() call".to_string()))?
        .map_err(|e| MonitorError::ReadError(format!("currentPrice() call failed: {}", e)))?;

        if result_price.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid currentPrice response".to_string(),
            ));
        }

        let current_price = U256::from_big_endian(&result_price[0..32]);

        // Get current block timestamp
        let block = self
            .provider
            .get_block(BlockNumber::Latest)
            .await
            .map_err(|e| MonitorError::Provider(format!("Failed to get block: {}", e)))?
            .ok_or_else(|| MonitorError::InvalidData("No latest block".to_string()))?;

        let now = block.timestamp.as_u64();
        let age_secs = now.saturating_sub(last_updated);

        let configured_cadence = self.get_oracle_cadence(&oracle_address);
        let is_stale = age_secs > configured_cadence;
        let is_frozen = age_secs > MAX_STALENESS_SECS;

        Ok(OracleStatus {
            oracle_address,
            itp_address,
            last_updated,
            current_price,
            age_secs,
            is_stale,
            is_frozen,
            configured_cadence,
        })
    }

