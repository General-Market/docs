    /// Scan all positions in a market and compute health factors
    pub async fn scan_positions(
        &self,
        market_id: [u8; 32],
    ) -> Result<Vec<PositionHealth>, MonitorError> {
        let borrowers = self
            .known_borrowers
            .get(&market_id)
            .cloned()
            .unwrap_or_default();

        if borrowers.is_empty() {
            debug!(
                market_id = %hex::encode(market_id),
                "No known borrowers for market"
            );
            return Ok(vec![]);
        }

        // Read market data once
        let (total_borrow_assets, total_borrow_shares, lltv) =
            self.read_market_data(market_id).await?;

        // Read oracle price from market params
        let oracle_address = self.read_market_oracle(market_id).await?;
        let oracle_price = self.read_oracle_price(oracle_address).await?;

        let mut positions = Vec::new();

        for borrower in borrowers {
            match self
                .read_position(
                    market_id,
                    borrower,
                    total_borrow_assets,
                    total_borrow_shares,
                    oracle_price,
                    lltv,
                )
                .await
            {
                Ok(Some(pos)) => positions.push(pos),
                Ok(None) => {} // No borrow position
                Err(e) => {
                    warn!(
                        borrower = ?borrower,
                        error = %e,
                        "Failed to read position"
                    );
                }
            }
        }

        Ok(positions)
    }

    /// Read market data from Morpho
    async fn read_market_data(
        &self,
        market_id: [u8; 32],
    ) -> Result<(U256, U256, U256), MonitorError> {
        let mut calldata = SELECTOR_MARKET.to_vec();
        calldata.extend_from_slice(&market_id);

        let tx = TransactionRequest::new()
            .to(self.morpho_address)
            .data(calldata);

        let result = tokio::time::timeout(self.rpc_timeout, self.provider.call(&tx.into(), None))
            .await
            .map_err(|_| MonitorError::Timeout("market() call".to_string()))?
            .map_err(|e| MonitorError::ReadError(format!("market() call failed: {}", e)))?;

        if result.len() < 192 {
            return Err(MonitorError::InvalidData(format!(
                "Invalid market data length: {}",
                result.len()
            )));
        }

        // Decode: totalSupplyAssets, totalSupplyShares, totalBorrowAssets, totalBorrowShares, ...
        let total_borrow_assets = U256::from_big_endian(&result[64..96]);
        let total_borrow_shares = U256::from_big_endian(&result[96..128]);

        // Read LLTV from market params
        let lltv = self.read_market_lltv(market_id).await?;

        Ok((total_borrow_assets, total_borrow_shares, lltv))
    }

    /// Read market LLTV from idToMarketParams
    async fn read_market_lltv(&self, market_id: [u8; 32]) -> Result<U256, MonitorError> {
        let mut calldata = SELECTOR_ID_TO_MARKET_PARAMS.to_vec();
        calldata.extend_from_slice(&market_id);

        let tx = TransactionRequest::new()
            .to(self.morpho_address)
            .data(calldata);

        let result = tokio::time::timeout(self.rpc_timeout, self.provider.call(&tx.into(), None))
            .await
            .map_err(|_| MonitorError::Timeout("idToMarketParams() call".to_string()))?
            .map_err(|e| MonitorError::ReadError(format!("idToMarketParams() call failed: {}", e)))?;

        if result.len() < 160 {
            return Err(MonitorError::InvalidData(format!(
                "Invalid idToMarketParams data length: {}",
                result.len()
            )));
        }

        // LLTV is at offset 128-160
        Ok(U256::from_big_endian(&result[128..160]))
    }

    /// Read market oracle address from idToMarketParams
    async fn read_market_oracle(&self, market_id: [u8; 32]) -> Result<Address, MonitorError> {
        let mut calldata = SELECTOR_ID_TO_MARKET_PARAMS.to_vec();
        calldata.extend_from_slice(&market_id);

        let tx = TransactionRequest::new()
            .to(self.morpho_address)
            .data(calldata);

        let result = tokio::time::timeout(self.rpc_timeout, self.provider.call(&tx.into(), None))
            .await
            .map_err(|_| MonitorError::Timeout("idToMarketParams() call".to_string()))?
            .map_err(|e| MonitorError::ReadError(format!("idToMarketParams() call failed: {}", e)))?;

        if result.len() < 96 {
            return Err(MonitorError::InvalidData(format!(
                "Invalid idToMarketParams data length: {}",
                result.len()
            )));
        }

        // Oracle is at offset 76-96 (third address, padded to 32 bytes)
        Ok(Address::from_slice(&result[76..96]))
    }

    /// Read oracle price
    async fn read_oracle_price(&self, oracle_address: Address) -> Result<U256, MonitorError> {
        let tx = TransactionRequest::new()
            .to(oracle_address)
            .data(SELECTOR_CURRENT_PRICE.to_vec());

        let result = tokio::time::timeout(self.rpc_timeout, self.provider.call(&tx.into(), None))
            .await
            .map_err(|_| MonitorError::Timeout("currentPrice() call".to_string()))?
            .map_err(|e| MonitorError::ReadError(format!("currentPrice() call failed: {}", e)))?;

        if result.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid currentPrice response".to_string(),
            ));
        }

        Ok(U256::from_big_endian(&result[0..32]))
    }

    /// Read a single position
    async fn read_position(
        &self,
        market_id: [u8; 32],
        borrower: Address,
        total_borrow_assets: U256,
        total_borrow_shares: U256,
        oracle_price: U256,
        lltv: U256,
    ) -> Result<Option<PositionHealth>, MonitorError> {
        let mut calldata = SELECTOR_POSITION.to_vec();
        calldata.extend_from_slice(&market_id);
        // Pad address to 32 bytes
        calldata.extend_from_slice(&[0u8; 12]);
        calldata.extend_from_slice(borrower.as_bytes());

        let tx = TransactionRequest::new()
            .to(self.morpho_address)
            .data(calldata);

        let result = tokio::time::timeout(self.rpc_timeout, self.provider.call(&tx.into(), None))
            .await
            .map_err(|_| MonitorError::Timeout("position() call".to_string()))?
            .map_err(|e| MonitorError::ReadError(format!("position() call failed: {}", e)))?;

        if result.len() < 96 {
            return Err(MonitorError::InvalidData(format!(
                "Invalid position data length: {}",
                result.len()
            )));
        }

        // Position returns: supplyShares, borrowShares, collateral
        let _supply_shares = U256::from_big_endian(&result[0..32]);
        let borrow_shares = U256::from_big_endian(&result[32..64]);
        let collateral = U256::from_big_endian(&result[64..96]);

        // Skip positions with no borrows
        if borrow_shares.is_zero() {
            return Ok(None);
        }

        // Convert borrow shares to assets
        let debt_assets = if total_borrow_shares.is_zero() {
            U256::zero()
        } else {
            borrow_shares
                .checked_mul(total_borrow_assets)
                .unwrap_or(U256::MAX)
                .checked_div(total_borrow_shares)
                .unwrap_or(U256::zero())
        };

        // Compute health factor
        let health_factor =
            compute_health_factor(collateral, debt_assets, lltv, oracle_price);

        // Classify health status
        let status = classify_health_status(health_factor, &self.alert_config);

        Ok(Some(PositionHealth {
            borrower,
            market_id,
            collateral,
            borrow_shares,
            debt_assets,
            health_factor,
            status,
        }))
    }

    /// Run scan cycle with externally-provided asset stress data from SERM
    pub async fn run_scan_cycle_with_stress(
        &self,
        external_stress: &HashMap<[u8; 32], f64>,
        external_nav_drops: &HashMap<[u8; 32], f64>,
    ) -> Result<HealthReport, MonitorError> {
        let mut report = self.run_scan_cycle().await?;
        // Recompute crisis levels with actual stress data
        let crisis_levels = compute_crisis_levels(
            &report.positions,
            &self.market_ids,
            external_stress,
            external_nav_drops,
        );
        report.crisis_levels = crisis_levels;
        Ok(report)
    }

