    /// Read vault metrics from MetaMorpho
    pub async fn read_vault_metrics(&self) -> Result<VaultMetrics, MonitorError> {
        // Read totalAssets
        let tx_assets = TransactionRequest::new()
            .to(self.vault_address)
            .data(SELECTOR_TOTAL_ASSETS.to_vec());

        let result_assets = tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_assets.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("totalAssets() call".to_string()))?
        .map_err(|e| MonitorError::ReadError(format!("totalAssets() call failed: {}", e)))?;

        if result_assets.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid totalAssets response".to_string(),
            ));
        }

        let total_assets = U256::from_big_endian(&result_assets[0..32]);

        // Read totalSupply
        let tx_supply = TransactionRequest::new()
            .to(self.vault_address)
            .data(SELECTOR_TOTAL_SUPPLY.to_vec());

        let result_supply = tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_supply.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("totalSupply() call".to_string()))?
        .map_err(|e| MonitorError::ReadError(format!("totalSupply() call failed: {}", e)))?;

        if result_supply.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid totalSupply response".to_string(),
            ));
        }

        let total_supply = U256::from_big_endian(&result_supply[0..32]);

        // Read idle assets
        let tx_idle = TransactionRequest::new()
            .to(self.vault_address)
            .data(SELECTOR_IDLE.to_vec());

        let result_idle = tokio::time::timeout(
            self.rpc_timeout,
            self.provider.call(&tx_idle.into(), None),
        )
        .await
        .map_err(|_| MonitorError::Timeout("idle() call".to_string()))?
        .map_err(|e| MonitorError::ReadError(format!("idle() call failed: {}", e)))?;

        if result_idle.len() < 32 {
            return Err(MonitorError::InvalidData(
                "Invalid idle response".to_string(),
            ));
        }

        let idle_assets = U256::from_big_endian(&result_idle[0..32]);

        // Compute utilization: (totalAssets - idle) * 100 / totalAssets
        let utilization_pct = if total_assets.is_zero() {
            0u8
        } else {
            let utilized = total_assets.saturating_sub(idle_assets);
            let util = utilized
                .checked_mul(U256::from(100))
                .unwrap_or(U256::MAX)
                .checked_div(total_assets)
                .unwrap_or(U256::zero());
            util.as_u64().min(100) as u8
        };

        let high_utilization = utilization_pct > self.alert_config.high_utilization_pct;
        let markets_count = self.market_ids.len();

        Ok(VaultMetrics {
            total_assets,
            total_supply,
            idle_assets,
            utilization_pct,
            markets_count,
            high_utilization,
        })
    }

