/// Per-market crisis assessment input
pub struct MarketCrisisInput {
    /// Average health factor across all positions in this market
    pub avg_health_factor: f64,
    /// Whether any position is liquidatable (HF < 1.0)
    pub has_liquidatable: bool,
    /// Asset stress score (0.0 = no stress, 5.0 = max)
    pub asset_stress: f64,
    /// NAV drop over last 24h as a fraction (0.15 = 15% drop)
    pub nav_drop_24h: f64,
}

/// Determine crisis level for a market based on position health and stress data
///
/// Levels per architecture doc:
/// - Normal: all HF > 1.3, no asset stress
/// - Elevated: avg HF < 1.3 OR any asset stress > 1
/// - Stress: avg HF < 1.15 OR any asset stress > 3
/// - Emergency: any liquidatable OR asset stress > 4 OR NAV drop > 15%
pub fn determine_crisis_level(input: &MarketCrisisInput) -> CrisisLevel {
    // Emergency triggers (check first — most severe)
    if input.has_liquidatable || input.asset_stress > 4.0 || input.nav_drop_24h > 0.15 {
        return CrisisLevel::Emergency;
    }

    // Stress triggers
    if input.avg_health_factor < 1.15 || input.asset_stress > 3.0 {
        return CrisisLevel::Stress;
    }

    // Elevated triggers
    if input.avg_health_factor < 1.3 || input.asset_stress > 1.0 {
        return CrisisLevel::Elevated;
    }

    CrisisLevel::Normal
}

/// Compute crisis levels for all markets from position health data
///
/// Returns map of market_id (hex) → CrisisLevel.
/// For markets with no positions, defaults to Normal.
/// Asset stress and NAV drop are optional inputs (default 0.0 if not available).
pub fn compute_crisis_levels(
    positions: &[PositionHealth],
    market_ids: &[[u8; 32]],
    asset_stress: &HashMap<[u8; 32], f64>,
    nav_drops: &HashMap<[u8; 32], f64>,
) -> HashMap<String, CrisisLevel> {
    let mut levels = HashMap::new();

    for market_id in market_ids {
        let market_positions: Vec<&PositionHealth> = positions
            .iter()
            .filter(|p| &p.market_id == market_id)
            .collect();

        let (avg_hf, has_liquidatable) = if market_positions.is_empty() {
            (f64::INFINITY, false)
        } else {
            let sum_hf: f64 = market_positions.iter().map(|p| p.health_factor).sum();
            let avg = sum_hf / market_positions.len() as f64;
            let liquidatable = market_positions
                .iter()
                .any(|p| p.status == HealthStatus::Liquidatable);
            (avg, liquidatable)
        };

        let stress = asset_stress.get(market_id).copied().unwrap_or(0.0);
        let nav_drop = nav_drops.get(market_id).copied().unwrap_or(0.0);

        let input = MarketCrisisInput {
            avg_health_factor: avg_hf,
            has_liquidatable,
            asset_stress: stress,
            nav_drop_24h: nav_drop,
        };

        let level = determine_crisis_level(&input);
        let key = format!("0x{}", hex::encode(market_id));
        levels.insert(key, level);
    }

    levels
}

