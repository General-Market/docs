/// Configuration for alert thresholds
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AlertConfig {
    /// Health factor below which to generate WARNING
    pub warning_health_factor: f64,
    /// Health factor below which to generate CRITICAL
    pub critical_health_factor: f64,
    /// Oracle staleness thresholds per risk tier (in seconds)
    pub oracle_stale_secs: HashMap<RiskTier, u64>,
    /// Utilization percentage above which to flag high utilization
    pub high_utilization_pct: u8,
}

impl Default for AlertConfig {
    fn default() -> Self {
        let mut oracle_stale_secs = HashMap::new();
        oracle_stale_secs.insert(RiskTier::A, TIER_A_CADENCE_SECS);
        oracle_stale_secs.insert(RiskTier::B, TIER_B_CADENCE_SECS);
        oracle_stale_secs.insert(RiskTier::C, TIER_C_CADENCE_SECS);
        oracle_stale_secs.insert(RiskTier::D, TIER_D_CADENCE_SECS);

        Self {
            warning_health_factor: DEFAULT_WARNING_HEALTH_FACTOR,
            critical_health_factor: DEFAULT_CRITICAL_HEALTH_FACTOR,
            oracle_stale_secs,
            high_utilization_pct: DEFAULT_HIGH_UTILIZATION_PCT,
        }
    }
}

