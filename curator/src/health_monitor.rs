/// Compute health factor for a position
///
/// Formula: healthFactor = (collateral * oraclePrice * LLTV) / debt
///
/// Where:
/// - collateral is in collateral token units (18 decimals for ITP)
/// - oraclePrice is in Morpho format (36 decimals, adjusted for loan/collateral decimal diff)
/// - LLTV is in 1e18 format (e.g., 0.77e18 = 77%)
/// - debt is in loan token units (6 decimals for USDC)
pub fn compute_health_factor(
    collateral: U256,
    debt: U256,
    lltv: U256,
    oracle_price: U256,
) -> f64 {
    if debt.is_zero() {
        return f64::INFINITY;
    }

    // For precision, compute in U256 then convert to f64
    // numerator = collateral * price * lltv
    // denominator = debt * 1e18 (to match lltv scaling)
    //
    // But since price is already scaled for loan/collateral decimals,
    // and we want HF in human-readable form:
    // HF = (collateral * price / 1e36) * (lltv / 1e18) / debt

    // Simplified for f64 computation:
    let collateral_f = collateral.as_u128() as f64;
    let debt_f = debt.as_u128() as f64;
    let lltv_f = lltv.as_u128() as f64 / 1e18;
    let price_f = oracle_price.as_u128() as f64;

    // Price is scaled: 36 + loanDecimals - collateralDecimals = 36 + 6 - 18 = 24
    // So price is in 1e24 format
    // collateral (1e18) * price (1e24) = 1e42
    // debt (1e6) needs to match, so: 1e42 / 1e6 = 1e36
    // Therefore: HF = collateral * price * lltv / (debt * 1e36)
    let hf = (collateral_f * price_f * lltv_f) / (debt_f * 1e36);

    hf
}

/// Classify health status based on health factor
pub fn classify_health_status(health_factor: f64, config: &AlertConfig) -> HealthStatus {
    if health_factor < 1.0 {
        HealthStatus::Liquidatable
    } else if health_factor < config.critical_health_factor {
        HealthStatus::Critical
    } else if health_factor < config.warning_health_factor {
        HealthStatus::Warning
    } else {
        HealthStatus::Healthy
    }
}

/// Write a health report to a JSON file
