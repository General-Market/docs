export type EdgeCategory = 'information' | 'latency' | 'execution' | 'subsidy' | 'risk'

export interface EdgeSource {
  label: string
  url: string
}

export interface CompanyRow {
  slug: string
  name: string
  /** Short uppercase pill — keep under ~22 chars. */
  tag: string
  /** Magnitude in the topic's shared unit. */
  value: number
  /** Portion of `value` truly gated behind a real barrier. */
  gatedValue: number
  /** One-line "X vs Y" framing. */
  lane: string
  /** Phrase naming the barrier (contract, capital, employment, dealer balance sheet). */
  barrier: string
  sources: EdgeSource[]
}

export interface EdgeTopic {
  slug: string
  category: EdgeCategory
  name: string
  /** H3 above the chart — the knife sentence. */
  heading: string
  /** Lead paragraph below the heading — explains the unit and the bar legend. */
  lead: string
  /** Shared unit string. Every row's value is in this unit. */
  unit: string
  /** "No edge" caption shown on the General Market row. */
  generalMarketLabel: string
  rows: CompanyRow[]
}

