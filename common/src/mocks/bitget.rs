    #[tokio::test]
    async fn test_with_seed_reproducibility() {
        // Two mocks with the same seed should produce the same failure pattern
        let run_with_seed = |seed: u64| async move {
            let mock = MockBitgetBuilder::new()
                .with_seed(seed)
                .with_failure_rate(0.5)
                .with_latency(Duration::from_millis(1))
                .with_fill_delay(Duration::from_secs(10))
                .build();

            let mut results = vec![];
            for _ in 0..20 {
                let r = mock
                    .place_order(
                        "BTC/USDC".to_string(),
                        Side::Buy,
                        U256::from(100u64),
                        U256::from(50000u64),
                    )
                    .await;
                results.push(r.is_ok());
            }
            results
        };

        let results1 = run_with_seed(42).await;
        let results2 = run_with_seed(42).await;
        let results3 = run_with_seed(99).await;

        assert_eq!(results1, results2, "same seed must produce same failure pattern");
        // Different seed should (very likely) produce different pattern
        // With 20 trials at 50% rate, probability of identical sequences is ~1/2^20
        assert_ne!(results1, results3, "different seeds should produce different patterns");
    }

