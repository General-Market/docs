    #[tokio::test]
    async fn test_partial_fill_scenario() {
        let mock = MockBitgetBuilder::new()
            .with_latency(Duration::from_millis(1))
            .with_fill_delay(Duration::from_secs(10)) // Long delay - we'll manually fill
            .build();

        let total_amount = U256::from(1000u64) * U256::exp10(18);
        let order_id = mock
            .place_order(
                "BTC/USDC".to_string(),
                Side::Buy,
                total_amount,
                U256::from(50000u64) * U256::exp10(18),
            )
            .await
            .unwrap();

        // Order should be pending initially
        let status = mock.get_order_status(order_id).await.unwrap();
        assert_eq!(status, OrderStatus::Pending);

        // Simulate partial fill (50% of the order)
        let partial_amount = U256::from(500u64) * U256::exp10(18);
        let fill_price = U256::from(50000u64) * U256::exp10(18);
        let filled = mock.simulate_fill(order_id, partial_amount, fill_price).await;
        assert!(filled, "partial fill should succeed");

        // Should have one fill
        let fills = mock.get_fills(order_id).await.unwrap();
        assert_eq!(fills.len(), 1);
        assert_eq!(fills[0].fill_amount, partial_amount);

        // Status should still be Pending (not fully filled yet)
        let status = mock.get_order_status(order_id).await.unwrap();
        assert_eq!(status, OrderStatus::Pending);

        // Simulate remaining fill
        let filled = mock.simulate_fill(order_id, partial_amount, fill_price).await;
        assert!(filled, "remaining fill should succeed");

        // Now should be fully filled
        let status = mock.get_order_status(order_id).await.unwrap();
        assert_eq!(status, OrderStatus::Filled);

        // Should have two fills
        let fills = mock.get_fills(order_id).await.unwrap();
        assert_eq!(fills.len(), 2);
    }

