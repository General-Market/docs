/// Spread configuration for different asset types
#[derive(Debug, Clone)]
pub struct SpreadConfig {
    /// Spread in basis points (1 bp = 0.01%)
    pub spread_bps: u32,
}

impl SpreadConfig {
    /// Stablecoin spread (5 bps = 0.05%)
    pub const STABLECOIN: SpreadConfig = SpreadConfig { spread_bps: 5 };
    /// Major asset spread (10 bps = 0.10%)
    pub const MAJOR: SpreadConfig = SpreadConfig { spread_bps: 10 };
    /// Other asset spread (25 bps = 0.25%)
    pub const OTHER: SpreadConfig = SpreadConfig { spread_bps: 25 };
}

/// Order in the mock order book
#[derive(Debug, Clone)]
pub struct MockOrder {
    pub id: OrderId,
    pub pair: String,
    pub side: Side,
    pub amount: U256,
    pub price: U256,
    pub status: OrderStatus,
    pub filled_amount: U256,
    pub created_at: u64,
}

/// Fill generated by the mock
#[derive(Debug, Clone)]
pub struct MockFill {
    pub order_id: OrderId,
    pub fill_price: U256,
    pub fill_amount: U256,
    pub timestamp: u64,
}

/// Internal state for MockBitget
#[derive(Debug, Default)]
struct MockBitgetState {
    /// Orders by ID
    orders: HashMap<OrderId, MockOrder>,
    /// Fills by order ID
    fills: HashMap<OrderId, Vec<MockFill>>,
    /// Balances by asset
    balances: HashMap<String, U256>,
}

/// Configuration for MockBitget behavior
#[derive(Debug, Clone)]
pub struct MockBitgetConfig {
    /// Latency to add to all operations
    pub latency: Option<Duration>,
    /// Random failure rate (0.0-1.0)
    pub failure_rate: f64,
    /// Force next operation to fail with this error
    pub next_error: Option<MockError>,
    /// Spread configuration per pair
    pub spreads: HashMap<String, SpreadConfig>,
    /// Order book depth
    pub depth: U256,
    /// Fill delay (default 100ms)
    pub fill_delay: Duration,
    /// Random seed for reproducibility
    pub seed: Option<u64>,
}

impl Default for MockBitgetConfig {
    fn default() -> Self {
        Self {
            latency: Some(Duration::from_millis(100)), // Default latency
            failure_rate: 0.0,
            next_error: None,
            spreads: HashMap::new(),
            depth: U256::from(1_000_000u64) * U256::exp10(18), // 1M depth
            fill_delay: Duration::from_millis(100),
            seed: None,
        }
    }
}

/// Mock implementation of Bitget exchange client
///
/// Simulates order placement and fill mechanics with configurable
/// spread based on asset type.
pub struct MockBitget {
    state: Arc<RwLock<MockBitgetState>>,
    config: Arc<RwLock<MockBitgetConfig>>,
    order_counter: AtomicU64,
    /// Shutdown flag for cancelling background fill tasks
    shutdown: Arc<AtomicBool>,
    /// Seeded RNG for reproducible failure injection
    rng: Arc<Mutex<StdRng>>,
}

impl MockBitget {
    /// Check for injected errors or random failures
    async fn maybe_fail(&self) -> Result<(), Error> {
        let mut config = self.config.write().await;

        // Check for forced next error
        if let Some(err) = config.next_error.take() {
            return Err(err.into());
        }

        // Check for random failure
        if config.failure_rate > 0.0 {
            let mut rng = self.rng.lock().await;
            if rng.gen::<f64>() < config.failure_rate {
                return Err(MockError::SimulatedFailure(config.failure_rate).into());
            }
        }

        Ok(())
    }

    /// Apply configured latency
    async fn apply_latency(&self) {
        let config = self.config.read().await;
        if let Some(latency) = config.latency {
            tokio::time::sleep(latency).await;
        }
    }

    /// Get spread for a pair
    async fn get_spread(&self, pair: &str) -> SpreadConfig {
        let config = self.config.read().await;

        // Check for explicit spread config
        if let Some(spread) = config.spreads.get(pair) {
            return spread.clone();
        }

        // Determine by pair name - check major assets first
        // (BTC/USDC should be major, not stablecoin)
        let pair_upper = pair.to_uppercase();
        if pair_upper.contains("BTC") || pair_upper.contains("ETH") {
            SpreadConfig::MAJOR
        } else if pair_upper.contains("USDC")
            || pair_upper.contains("USDT")
            || pair_upper.contains("DAI")
        {
            SpreadConfig::STABLECOIN
        } else {
            SpreadConfig::OTHER
        }
    }

    /// Set latency for all operations
    pub async fn set_latency(&self, latency: Duration) {
        self.config.write().await.latency = Some(latency);
    }

    /// Set random failure rate (0.0-1.0)
    pub async fn set_failure_rate(&self, rate: f64) {
        self.config.write().await.failure_rate = rate.clamp(0.0, 1.0);
    }

    /// Set spread for a specific pair
    pub async fn set_spread(&self, pair: &str, spread_bps: u32) {
        self.config
            .write()
            .await
            .spreads
            .insert(pair.to_string(), SpreadConfig { spread_bps });
    }

    /// Force the next operation to fail with a specific error
    pub async fn set_next_error(&self, error: MockError) {
        self.config.write().await.next_error = Some(error);
    }

    /// Add balance to an asset
    pub async fn add_balance(&self, asset: &str, amount: U256) {
        let mut state = self.state.write().await;
        let balance = state.balances.entry(asset.to_string()).or_insert(U256::zero());
        *balance = balance.saturating_add(amount);
    }

    /// Simulate a fill for an order (test helper)
    /// Returns false if order not found, already filled, cancelled, or expired
    pub async fn simulate_fill(&self, order_id: OrderId, fill_amount: U256, fill_price: U256) -> bool {
        let mut state = self.state.write().await;

        if let Some(order) = state.orders.get_mut(&order_id) {
            // Can only fill Pending or Batched orders
            if order.status != OrderStatus::Pending && order.status != OrderStatus::Batched {
                return false;
            }

            let fill = MockFill {
                order_id,
                fill_amount,
                fill_price,
                timestamp: std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .unwrap()
                    .as_secs(),
            };

            order.filled_amount = order.filled_amount.saturating_add(fill_amount);

            if order.filled_amount >= order.amount {
                order.status = OrderStatus::Filled;
            }

            state.fills.entry(order_id).or_default().push(fill);
            true
        } else {
            false
        }
    }

    /// Get all orders (test helper)
    pub async fn get_all_orders(&self) -> Vec<MockOrder> {
        self.state.read().await.orders.values().cloned().collect()
    }

    /// Cancel an order (returns error if already filled or not found)
    pub async fn cancel_order(&self, order_id: OrderId) -> Result<(), Error> {
        self.maybe_fail().await?;
        self.apply_latency().await;

        let mut state = self.state.write().await;
        match state.orders.get_mut(&order_id) {
            Some(order) => {
                if order.status == OrderStatus::Filled {
                    Err(
                        MockError::InvalidState("cannot cancel filled order".to_string())
                            .into(),
                    )
                } else {
                    order.status = OrderStatus::Cancelled;
                    Ok(())
                }
            }
            None => Err(MockError::OrderNotFound(format!("{}", order_id)).into()),
        }
    }

    /// Batch an order (move from Pending to Batched status)
    /// Used to simulate order being included in a batch for execution
    pub async fn batch_order(&self, order_id: OrderId) -> Result<(), Error> {
        let mut state = self.state.write().await;
        match state.orders.get_mut(&order_id) {
            Some(order) => {
                if order.status != OrderStatus::Pending {
                    Err(MockError::InvalidState(format!(
                        "cannot batch order with status {:?}",
                        order.status
                    ))
                    .into())
                } else {
                    order.status = OrderStatus::Batched;
                    Ok(())
                }
            }
            None => Err(MockError::OrderNotFound(format!("{}", order_id)).into()),
        }
    }

    /// Expire an order (move to Expired status)
    /// Used to simulate order deadline passing
    pub async fn expire_order(&self, order_id: OrderId) -> Result<(), Error> {
        let mut state = self.state.write().await;
        match state.orders.get_mut(&order_id) {
            Some(order) => match order.status {
                OrderStatus::Pending | OrderStatus::Batched => {
                    order.status = OrderStatus::Expired;
                    Ok(())
                }
                OrderStatus::Filled => {
                    Err(MockError::InvalidState("cannot expire filled order".to_string()).into())
                }
                OrderStatus::Cancelled => {
                    Err(MockError::InvalidState("cannot expire cancelled order".to_string()).into())
                }
                OrderStatus::Expired => {
                    Err(MockError::InvalidState("order already expired".to_string()).into())
                }
            },
            None => Err(MockError::OrderNotFound(format!("{}", order_id)).into()),
        }
    }
}

#[async_trait]
impl APClient for MockBitget {
    async fn place_order(
        &self,
        pair: String,
        side: Side,
        amount: U256,
        price: U256,
    ) -> Result<OrderId, Error> {
        self.maybe_fail().await?;
        self.apply_latency().await;

        // Validate amount
        if amount.is_zero() {
            return Err(MockError::InvalidState("order amount cannot be zero".to_string()).into());
        }

        // Enforce order book depth limit
        let depth = self.config.read().await.depth;
        if amount > depth {
            return Err(MockError::InvalidState(format!(
                "order amount {} exceeds order book depth {}",
                amount, depth
            ))
            .into());
        }

        // Generate order ID
        let order_id = U256::from(self.order_counter.fetch_add(1, Ordering::SeqCst));

        // Get spread for this pair
        let spread = self.get_spread(&pair).await;

        // Calculate adjusted fill price based on spread (integer math, no float precision loss)
        let spread_adjustment = price * U256::from(spread.spread_bps) / U256::from(10000);
        let fill_price = match side {
            Side::Buy => price.saturating_add(spread_adjustment / U256::from(2)),
            Side::Sell => price.saturating_sub(spread_adjustment / U256::from(2)),
        };

        let order = MockOrder {
            id: order_id,
            pair: pair.clone(),
            side,
            amount,
            price: fill_price,
            status: OrderStatus::Pending,
            filled_amount: U256::zero(),
            created_at: std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_secs(),
        };

        {
            let mut state = self.state.write().await;

            // Enforce balance if balances are configured
            if !state.balances.is_empty() {
                let parts: Vec<&str> = pair.split('/').collect();
                if parts.len() == 2 {
                    let (check_asset, required) = match side {
                        Side::Buy => {
                            // Buying base with quote: cost = amount * price / 10^18
                            let cost = amount
                                .checked_mul(price)
                                .map(|v| v / U256::exp10(18))
                                .unwrap_or(U256::MAX);
                            (parts[1], cost)
                        }
                        Side::Sell => (parts[0], amount),
                    };
                    let balance = state
                        .balances
                        .get(check_asset)
                        .copied()
                        .unwrap_or(U256::zero());
                    if balance < required {
                        return Err(MockError::InsufficientBalance(format!(
                            "{}: need {} have {}",
                            check_asset, required, balance
                        ))
                        .into());
                    }
                    // Deduct balance
                    if let Some(bal) = state.balances.get_mut(check_asset) {
                        *bal = bal.saturating_sub(required);
                    }
                }
            }

            state.orders.insert(order_id, order);
        }

        // Schedule automatic fill after delay
        let state_clone = self.state.clone();
        let config_clone = self.config.clone();
        let shutdown_clone = self.shutdown.clone();
        tokio::spawn(async move {
            let fill_delay = config_clone.read().await.fill_delay;
            tokio::time::sleep(fill_delay).await;

            // Check if shutdown was requested
            if shutdown_clone.load(Ordering::SeqCst) {
                return;
            }

            let mut state = state_clone.write().await;
            if let Some(order) = state.orders.get_mut(&order_id) {
                if order.status == OrderStatus::Pending {
                    order.filled_amount = order.amount;
                    order.status = OrderStatus::Filled;

                    let fill = MockFill {
                        order_id,
                        fill_amount: order.amount,
                        fill_price: order.price,
                        timestamp: std::time::SystemTime::now()
                            .duration_since(std::time::UNIX_EPOCH)
                            .unwrap()
                            .as_secs(),
                    };
                    state.fills.entry(order_id).or_default().push(fill);
                }
            }
        });

        Ok(order_id)
    }

    async fn get_fills(&self, order_id: OrderId) -> Result<Vec<Fill>, Error> {
        self.maybe_fail().await?;
        self.apply_latency().await;

        let state = self.state.read().await;
        let fills = state.fills.get(&order_id).cloned().unwrap_or_default();

        // Convert MockFill to Fill
        Ok(fills
            .into_iter()
            .map(|f| Fill {
                order_id: f.order_id,
                fill_price: f.fill_price,
                fill_amount: f.fill_amount,
                cycle_number: U256::zero(),
                tx_hash: TxHash::zero(),
            })
            .collect())
    }

    async fn get_order_status(&self, order_id: OrderId) -> Result<OrderStatus, Error> {
        self.maybe_fail().await?;
        self.apply_latency().await;

        let state = self.state.read().await;
        state
            .orders
            .get(&order_id)
            .map(|o| o.status)
            .ok_or_else(|| MockError::OrderNotFound(format!("{}", order_id)).into())
    }
}

impl Drop for MockBitget {
    fn drop(&mut self) {
        // Signal shutdown to all spawned fill tasks
        self.shutdown.store(true, Ordering::SeqCst);
    }
}

/// Builder for MockBitget
pub struct MockBitgetBuilder {
    balances: HashMap<String, U256>,
    config: MockBitgetConfig,
}

impl MockBitgetBuilder {
    /// Create a new builder with defaults
    pub fn new() -> Self {
        Self {
            balances: HashMap::new(),
            config: MockBitgetConfig::default(),
        }
    }

    /// Add initial balance for an asset
    pub fn with_balance(mut self, asset: &str, amount: U256) -> Self {
        self.balances.insert(asset.to_string(), amount);
        self
    }

    /// Set spread for a pair in basis points
    pub fn with_spread(mut self, pair: &str, spread_bps: u32) -> Self {
        self.config
            .spreads
            .insert(pair.to_string(), SpreadConfig { spread_bps });
        self
    }

    /// Set order book depth
    pub fn with_depth(mut self, depth: U256) -> Self {
        self.config.depth = depth;
        self
    }

    /// Set operation latency
    pub fn with_latency(mut self, latency: Duration) -> Self {
        self.config.latency = Some(latency);
        self
    }

    /// Set random failure rate
    pub fn with_failure_rate(mut self, rate: f64) -> Self {
        self.config.failure_rate = rate.clamp(0.0, 1.0);
        self
    }

    /// Set random seed for reproducibility
    pub fn with_seed(mut self, seed: u64) -> Self {
        self.config.seed = Some(seed);
        self
    }

    /// Set fill delay
    pub fn with_fill_delay(mut self, delay: Duration) -> Self {
        self.config.fill_delay = delay;
        self
    }

    /// Build the MockBitget
    pub fn build(self) -> MockBitget {
        let state = MockBitgetState {
            orders: HashMap::new(),
            fills: HashMap::new(),
            balances: self.balances,
        };

        let rng = match self.config.seed {
            Some(seed) => StdRng::seed_from_u64(seed),
            None => StdRng::from_entropy(),
        };

        MockBitget {
            state: Arc::new(RwLock::new(state)),
            config: Arc::new(RwLock::new(self.config)),
            order_counter: AtomicU64::new(1),
            shutdown: Arc::new(AtomicBool::new(false)),
            rng: Arc::new(Mutex::new(rng)),
        }
    }
}

impl Default for MockBitgetBuilder {
    fn default() -> Self {
        Self::new()
    }
}

